// features/anatomy/build.mjs
// Entry point Stella's anatomy skill calls via `node`.
// Reads a JSON spec from the first argument, builds an isometric
// SVG figure, writes an HTML file next to this script, and prints
// a JSON result the skill can return to the user.
//
// Usage:
//   node features/anatomy/build.mjs '{"example":"dial-indicator","theme":"dark"}'

import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as k from "./kit/iso-kit.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "out");

function readSpec() {
  const arg = process.argv[2];
  if (arg && arg !== "-") {
    try { return JSON.parse(arg); } catch (e) { return {}; }
  }
  return {};
}

function dialIndicator(spec) {
  const WIDTH = spec.width || 600;
  const HEIGHT = spec.height || 380;
  const theme = spec.theme || "dark";
  const PLATE = { x: -128, y: -64, w: 262, d: 128, r: 8 };
  const PLATE_H = 12; const FOOT_H = 5;
  const DIAL = [58, 0]; const DIAL_R = 20; const DIAL_Z = 82; const DIAL_H = 10;
  const BLOCKS = [18, 14, 10]; const STEP = 16; const BLOCK_W = 15.6;
  const CENTRE = -24 + BLOCK_W / 2;
  const STOPS = BLOCKS.map(function(_, i) { return DIAL[0] - CENTRE - STEP * i; });
  const startX = STOPS[0];

  const P = k.fitProjection(
    [...k.boxCorners(PLATE, -PLATE_H - FOOT_H, 0), [DIAL[0] + DIAL_R, 0, DIAL_Z + DIAL_H]],
    WIDTH, HEIGHT, { pad: 30, azimuth: 42 },
  );

  var dx = DIAL[0], dy = DIAL[1];
  var body = [];

  // ---- Plate with feet ----
  var cs = k.corners(PLATE, 2);
  body.push('<path class="iso-halo" d="' + k.haloOf(PLATE, -PLATE_H, 0, P) + '"/>');
  // Foot cylinders at corners
  var footCorners = k.corners(PLATE, 10);
  for (var i = 0; i < footCorners.length; i++) {
    var fc = footCorners[i];
    body.push(k.cylinder(fc[0], fc[1], 7, -PLATE_H - FOOT_H, -PLATE_H, P, 28, "lo", false));
    body.push(k.cylinder(fc[0], fc[1], 5.4, -PLATE_H, 0, P, 28, "mid", false));
  }
  body.push(k.slabOf(PLATE, -PLATE_H, 0, P, 8, "mid"));
  body.push(k.planOutline(k.insetPlan(PLATE, 5), 0, P, 1));
  var screws = k.corners(PLATE, 10);
  var screwRings = [];
  for (var i = 0; i < screws.length; i++) {
    screwRings.push(k.ring(screws[i][0], screws[i][1], 2.2, 0, P, 16));
  }
  body.push(k.lineSvg(screwRings.join(""), { tone: "lo" }));
  body.push(k.dotsSvg(screws.map(function(p) { return k.iso([p[0], p[1], 0], P); }), { size: 0.5 }));

  // ---- Dial cylinder ----
  body.push(k.cylinder(dx, dy, 2.9, 54, DIAL_Z - 54, P, 20, "mid", false));
  body.push(k.cylinder(dx, dy, DIAL_R, DIAL_Z, DIAL_Z + DIAL_H, P, 64, "lo", false));
  body.push(k.ring(dx, dy, DIAL_R - 2.2, DIAL_Z + DIAL_H, P, 64));
  var ticks = k.radialTicks(dx, dy, DIAL_R - 3, 50, 5, DIAL_Z + DIAL_H, [1.3, 2.8], P);
  body.push(k.lineSvg(ticks.minor, { tone: "lo" }));
  body.push(k.lineSvg(ticks.major, { tone: "mid" }));
  body.push(k.faceTextSvg(k.topMatrix(dx, dy + 9, DIAL_Z + DIAL_H, P, "x"), "0.01", { size: 2.4, tone: "lo", anchor: "middle" }));

  // ---- Needle ----
  var turn = spec.turn || 0.9;
  var angle = turn * Math.PI * 2;
  body.push('<path d="' + k.lineOnTop(
    [dx - Math.sin(angle) * 3.4, dy + Math.cos(angle) * 3.4],
    [dx + Math.sin(angle) * (DIAL_R - 4), dy - Math.cos(angle) * (DIAL_R - 4)],
    DIAL_Z + DIAL_H + 0.2, P
  ) + '" stroke="#fbbf24" stroke-width="1.1" fill="none"/>');

  var svg = k.figureSvg({
    width: WIDTH, height: HEIGHT,
    label: spec.fig || "Fig 1",
    body: body,
  });

  var keys = [
    { mark: "lit", label: "Plunger and needle: what moves when the height changes" },
    { mark: "raised", label: "Three gauge blocks, 18, 14 and 10 tall" },
  ];
  var keyHtml = keys.map(function(k2) {
    var bg = k2.mark === "lit" ? "#fbbf24" : "#94a3b8";
    return '<div class="key"><span class="mark" style="background:' + bg + ';"></span> ' + k2.label + "</div>";
  }).join("");

  var html = k.plateHtml({
    fig: spec.fig || "Fig 1",
    title: spec.title || "Dial indicator",
    hint: spec.hint || "Interactive isometric figure generated by Stella's anatomy skill",
    readout: spec.readout || "block 1 · reads 18.0 px",
    keys: keys,
    caption: spec.caption || "A dial indicator on a surface plate.",
    body: '<div class="iso-stage" tabindex="0" role="slider" aria-label="Dial indicator">' + svg + '</div>',
  });

  return { svg: svg, html: html, P: P, spec: spec };
}

const EXAMPLES = {
  "dial-indicator": dialIndicator,
};

function run() {
  var spec = readSpec();
  var example = spec.example || "dial-indicator";
  var builder = EXAMPLES[example];
  if (!builder) {
    process.stdout.write(JSON.stringify({
      ok: false,
      error: "Unknown example '" + example + "'. Known: " + Object.keys(EXAMPLES).join(", ") + ".",
    }));
    process.exit(1);
  }

  var result = builder(spec);
  mkdirSync(OUT, { recursive: true });
  var theme = spec.theme || "dark";
  var outName = "anatomy-" + example + "-" + theme + ".html";
  var outPath = join(OUT, outName);
  writeFileSync(outPath, result.html, "utf-8");

  process.stdout.write(JSON.stringify({
    ok: true,
    example: example,
    theme: theme,
    width: spec.width || 600,
    height: spec.height || 380,
    html_path: outPath,
    svg: result.svg,
    html: result.html,
    projection: result.P,
    note: "Figure generated by Stella's anatomy skill (self-contained Node.js kit).",
  }));
}

run();
