<#
.SYNOPSIS
    Bring .venv in line with requirements-lock.txt WITHOUT re-downloading
    everything.

.DESCRIPTION
    The naive `pip install -r requirements.txt` re-resolves and re-downloads
    the whole tree on every run. On a metered connection that is expensive and
    slow, and it yields a different tree each time.

    This script:
      1. Points pip at a persistent cache outside the repo, so a wheel is
         downloaded at most once across all sessions.
      2. Compares the lockfile against what is actually installed.
      3. Installs ONLY the difference (missing packages, version mismatches).
      4. Never upgrades something that already satisfies the pin.

    Safe to run repeatedly. With everything already correct it downloads
    nothing and exits quickly.

.PARAMETER Freeze
    Regenerate the lockfile from the current .venv. Use after deliberately
    changing the environment.

.PARAMETER Profile
    full  - everything in requirements.txt (default)
    core  - PyQt6 + psutil + numpy + pillow; enough to import the UI
    dev   - core + pytest + pyinstaller

.PARAMETER Check
    Report the delta and exit without installing anything.

.PARAMETER Offline
    Never touch the network. Fail loudly if something is missing.

.EXAMPLE
    .\scripts\sync_deps.ps1                 # install the delta
    .\scripts\sync_deps.ps1 -Check          # just show what is missing
    .\scripts\sync_deps.ps1 -Profile core   # light install
    .\scripts\sync_deps.ps1 -Freeze         # re-pin from current venv
#>
[CmdletBinding()]
param(
    [switch]$Freeze,
    [switch]$Check,
    [switch]$Offline,
    [ValidateSet('full', 'core', 'dev')]
    [string]$Profile = 'full'
)

$ErrorActionPreference = 'Stop'
$repo   = Split-Path -Parent $PSScriptRoot
$venvPy = Join-Path $repo '.venv\Scripts\python.exe'
$lock   = Join-Path $repo 'requirements-lock.txt'

if (-not (Test-Path $venvPy)) {
    Write-Host "No .venv found. Create it once with:" -ForegroundColor Red
    Write-Host "  py -3 -m venv .venv" -ForegroundColor Red
    exit 1
}

# ---------------------------------------------------------------------------
# Persistent cache: the single biggest data saver. Wheels live outside the
# repo so they survive a repo wipe and are reused across every later install.
# ---------------------------------------------------------------------------
$cache = Join-Path $env:USERPROFILE '.cache\stella-pip'
New-Item -ItemType Directory -Force -Path $cache | Out-Null
$env:PIP_CACHE_DIR = $cache

# Playwright otherwise downloads ~500MB of browser binaries we usually do not
# need at build time. Skipped unless the caller opts in.
if (-not $env:PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD) {
    $env:PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD = '1'
}

function Invoke-Pip {
    param([string[]]$PipArgs)
    & $venvPy -m pip @PipArgs
}

Write-Host "cache: $cache" -ForegroundColor DarkGray

# ---------------------------------------------------------------------------
# Freeze mode: the venv becomes the lockfile.
# ---------------------------------------------------------------------------
if ($Freeze) {
    Write-Host "==> Freezing current .venv into requirements-lock.txt" -ForegroundColor Cyan
    $lines = & $venvPy -m pip freeze --exclude-editable
    $header = @(
        '# Stella - pinned, reproducible dependency set.',
        '#',
        '# Generated by scripts/sync_deps.ps1 -Freeze. Do not hand-edit.',
        '# Source of truth for the build environment; requirements*.txt',
        '# describe intent, this file describes the exact working versions.',
        '',
        "# frozen from .venv at $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')"
    )
    ($header + $lines) | Set-Content -Path $lock -Encoding UTF8
    Write-Host "    wrote $lock ($($lines.Count) packages)" -ForegroundColor Green
    exit 0
}

# ---------------------------------------------------------------------------
# Work out what the selected profile needs.
# ---------------------------------------------------------------------------
$profileFiles = switch ($Profile) {
    'full' { @('requirements.txt', 'requirements-voice.txt', 'requirements-web.txt') }
    'core' { @('requirements-core.txt') }
    'dev'  { @('requirements-core.txt', 'requirements-dev.txt') }
}

# requirements-core.txt is always included - it is what the app imports first.
$reqs = @('requirements-core.txt') + ($profileFiles | Where-Object { $_ -ne 'requirements-core.txt' })
$reqs = $reqs | Where-Object { Test-Path (Join-Path $repo $_) } | Select-Object -Unique

Write-Host "==> profile: $Profile  (files: $($reqs -join ', '))" -ForegroundColor Cyan

# ---------------------------------------------------------------------------
# Delta detection. Ask pip what is ALREADY satisfied so we never re-download.
# ---------------------------------------------------------------------------
$installed = @{}
try {
    Invoke-Pip @('list', '--format=json', '--disable-pip-version-check') 2>$null |
        ForEach-Object { $rows = $_ | ConvertFrom-Json } |
        ForEach-Object { $installed[$_.name.ToLower()] = $_.version }
} catch {
    Write-Host "  (could not read installed packages: $_)" -ForegroundColor Yellow
}

# Dry-run each requirement file to discover what pip would fetch. This hits
# the index only for genuinely missing packages when the cache is cold; with
# a warm cache it is local.
$flag = if ($Check) { '--dry-run' } elseif ($Offline) { '--no-index' } else { '' }

$args = @('install', '--disable-pip-version-check')
if ($flag) { $args += $flag }
# Never silently upgrade a package that already meets its pin.
$args += @('--upgrade-strategy', 'only-if-needed')

if ($Check -or $Offline) {
    $args += '--quiet'
    $args += '--report'
    $args += (Join-Path $env:TEMP 'stella-pip-delta.json')
}

foreach ($r in $reqs) { $args += '-r'; $args += (Join-Path $repo $r) }

if ($Offline -and -not $env:PIP_NO_INDEX) { $args += '--no-index' }

Write-Host "==> resolving delta..." -ForegroundColor Cyan
Invoke-Pip $args
$code = $LASTEXITCODE

if ($Check) {
    if (Test-Path (Join-Path $env:TEMP 'stella-pip-delta.json')) {
        $report = Get-Content (Join-Path $env:TEMP 'stella-pip-delta.json') -Raw | ConvertFrom-Json
        if ($report.install) {
            Write-Host ""
            Write-Host "Would download/install:" -ForegroundColor Yellow
            foreach ($i in $report.install) {
                $dl = $i.download_info.url
                $size = if ($i.metadata) { '' } else { '' }
                Write-Host ("   {0}=={1}" -f $i.metadata.name, $i.metadata.version)
            }
        } else {
            Write-Host "Nothing to do - environment already matches." -ForegroundColor Green
        }
    }
    exit 0
}

if ($code -ne 0) {
    Write-Host ""
    Write-Host "Dependency sync failed (exit $code)." -ForegroundColor Red
    if ($Offline) {
        Write-Host "Run without -Offline when you have a connection." -ForegroundColor Yellow
    }
    exit $code
}

Write-Host ""
Write-Host "Dependencies in sync. Cache kept at:" -ForegroundColor Green
Write-Host "  $cache" -ForegroundColor Green
Write-Host "Next run installs only what changed - nothing else is downloaded." -ForegroundColor DarkGray
exit 0